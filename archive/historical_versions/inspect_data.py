import pandas as pd
mc = pd.read_parquet('data/processed/master_canonical.parquet')
print('COLUMNS:', list(mc.columns))
print()
print('FREQ+UNIT+VARS (unique per variable_id):')
print(mc[['variable_id','frequency','unit_code','period','value','source','source_dataset']].drop_duplicates('variable_id').sort_values('variable_id').to_string())
print()
print('FREQ value counts:')
print(mc['frequency'].value_counts())
print()
print('real_gdp sample:')
print(mc[mc['variable_id']=='real_gdp'].sort_values('period').tail(8).to_string())
print()
print('france_real_exports sample:')
print(mc[mc['variable_id']=='france_real_exports'].sort_values('period').tail(8).to_string())
print()
print('inflation sample (freq+unit+value):')
print(mc[mc['variable_id']=='inflation'].sort_values('period').tail(8).to_string())
print()
print('france_10y_government_rate sample:')
print(mc[mc['variable_id']=='france_10y_government_rate'].sort_values('period').tail(8).to_string())
print()
print('france_trade_balance sample (freq+unit+value):')
print(mc[mc['variable_id']=='france_trade_balance'].sort_values('period').tail(8).to_string())
